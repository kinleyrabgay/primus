#!/usr/bin/env node
/**
 * Generates cli/registry.json by scanning src/components/*.
 *
 * - `dependencies`: other primus components imported via '@selisedev/primus-beta/components/<name>'
 * - `npm`: third-party runtime peers imported by the component (anything that is
 *   not @angular/*, @selisedev/primus-beta/*, @primeuix/*, rxjs, or a relative path)
 *
 * Run from the repo root:  node cli/build-registry.mjs
 * CI check:                node cli/build-registry.mjs --check   (exit 1 if stale)
 */
import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const SRC = join(ROOT, 'src');
const COMPONENTS = join(SRC, 'components');
const OUT = join(__dirname, 'registry.json');
const check = process.argv.includes('--check');

const IGNORED_NPM = new Set(['rxjs', 'tslib']);
const version = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).version;

const tsFilesIn = (dir) => {
    const out = [];
    for (const entry of readdirSync(dir)) {
        const p = join(dir, entry);
        if (statSync(p).isDirectory()) out.push(...tsFilesIn(p));
        else if (entry.endsWith('.ts') && !entry.endsWith('.spec.ts')) out.push(p);
    }
    return out;
};

// static `from '...'` imports AND dynamic `import('...')` (e.g. editor lazy-loads quill)
const IMPORT_RE = /(?:from\s+|import\()\s*['"]([^'"]+)['"]/g;

const components = {};
for (const name of readdirSync(COMPONENTS).sort()) {
    const dir = join(COMPONENTS, name);
    if (!statSync(dir).isDirectory()) continue;

    const deps = new Set();
    const npm = new Set();

    for (const file of tsFilesIn(dir)) {
        const code = readFileSync(file, 'utf8');
        for (const [, spec] of code.matchAll(IMPORT_RE)) {
            const compMatch = spec.match(/^@selisedev\/primus-beta\/components\/([\w-]+)/);
            if (compMatch) {
                if (compMatch[1] !== name) deps.add(compMatch[1]);
                continue;
            }
            if (spec.startsWith('.') || spec.startsWith('@selisedev/primus-beta/') || spec.startsWith('@primeuix/') || spec.startsWith('@angular/')) continue;
            const pkg = spec.startsWith('@') ? spec.split('/').slice(0, 2).join('/') : spec.split('/')[0];
            if (!IGNORED_NPM.has(pkg)) npm.add(pkg);
        }
    }

    components[name] = {
        dir: `components/${name}`,
        dependencies: [...deps].sort(),
        ...(npm.size ? { npm: [...npm].sort() } : {})
    };
}

const registry = {
    $comment: 'GENERATED by cli/build-registry.mjs — do not edit by hand. core/ and theme/ are installed wholesale by `primus init`, so only cross-component and npm dependencies are listed.',
    version,
    sourceRoot: 'src',
    components
};

const next = JSON.stringify(registry, null, 4) + '\n';
if (check) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== next) {
        console.error('✗ cli/registry.json is stale — run `node cli/build-registry.mjs`');
        process.exit(1);
    }
    console.log('✓ registry up to date');
} else {
    writeFileSync(OUT, next);
    const n = Object.keys(components).length;
    const withDeps = Object.values(components).filter((c) => c.dependencies.length).length;
    console.log(`✓ registry written: ${n} components (${withDeps} with cross-component deps)`);
}
